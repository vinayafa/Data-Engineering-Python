# Variables make your code easier to maintain.
# You can assign a new value to the same variable name at any time.

name = "Vinay Kumar"
language = "python"
print("My name is", name)
print(name, "is learning", language)
print(name, "wants to become", language, "expert")

# Reuse the same variable names with different values.
name = "TIllu"
language = "JavaScript"
print("My name is", name)
print(name, "is learning", language)
print(name, "wants to become", language, "expert")

