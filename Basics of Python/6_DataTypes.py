# Data Types in Python
# Each variable here stores a different type of value.

a = 10          # int: whole number
b = 3.15        # float: decimal number
c = "Hello"    # str: text string
d = 'Hi'        # str: text string using single quotes
e = '12345'     # str: digits stored as text, not a number
f = True        # bool: boolean value True
g = False       # bool: boolean value False
h = None        # None: no value / nothing
i = ""        # empty string: has length 0
j = " "       # string with a single space character

# Remember:
# - Strings must be quoted.
# - Numbers can be ints or floats.
# - True and False are the only boolean values.
# - None means "no value" rather than blank text.


