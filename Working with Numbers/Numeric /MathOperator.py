# Arithmetic operators examples

# Addition: adds two numbers.
print(2 + 3)

# Subtraction: subtracts the right value from the left.
print(5 - 3)

# Multiplication: multiplies two numbers.
print(2 * 3)

# Division: true division returns a float result.
print(7 / 2)

# Floor division: divides and rounds down to the nearest whole number.
print(7 // 2)

# Modulo: returns the remainder after integer division.
print(7 % 2)

# Exponentiation: left raised to the power of right (2 to the power 3).
print(2 ** 3)

x = 2
# Augmented assignment: add and assign in one step (x = x + 3).
x += 3
print(x)

# Augmented assignment: multiply and assign in one step (x = x * 2).
x *= 2
print(x)


# Summary definitions:
# - `+` addition, `-` subtraction, `*` multiplication, `/` true division (float result)
# - `//` floor division (rounds down), `%` modulo (remainder), `**` exponentiation (power)
# - Augmented assignments like `+=`, `-=`, `*=`, `/=` update the variable in-place.